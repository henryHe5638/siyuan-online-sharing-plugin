/**
 * 把 Vite 构建出的 viewer 打包成单个 HTML 字符串。
 *
 * 插件最终要往分享目录里写一个 `index.html`。如果保留 Vite 的
 * `viewer/*.js`、`viewer/*.css` 外链，插件就必须逐个复制这些文件；
 * 这里直接内联，插件只写一个文件即可。
 *
 * 注意：必须在 `pnpm build:viewer` 之后运行。
 */
import {mkdir, readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "viewer", "dist");
const outFile = path.join(root, "plugin", "src", "generated", "viewer-html.ts");

let html = await readFile(path.join(dist, "index.html"), "utf8");

// 1. 把 <link rel="stylesheet" href="./viewer/xxx.css"> 替换为 <style>。
const cssMatches = [...html.matchAll(/<link[^>]+href="([^"]+\.css)"[^>]*>/g)];
for (const match of cssMatches) {
    const href = match[1].replace(/^\.\//, "");
    const css = await readFile(path.join(dist, href), "utf8");
    html = html.replace(match[0], `<style>\n${css}\n</style>`);
}

// 2. 把 <script type="module" src="./viewer/xxx.js"> 替换为内联 module。
//    内联脚本里如果出现字面量 `</script>` 会提前结束标签，需要转义。
const jsMatches = [...html.matchAll(/<script[^>]+src="([^"]+\.js)"[^>]*><\/script>/g)];
for (const match of jsMatches) {
    const src = match[1].replace(/^\.\//, "");
    let js = await readFile(path.join(dist, src), "utf8");
    js = js.replace(/<\/script>/gi, "<\\/script>");
    html = html.replace(match[0], `<script type="module">\n${js}\n</script>`);
}

if (cssMatches.length === 0 || jsMatches.length === 0) {
    throw new Error("viewer/dist/index.html does not contain the expected CSS/JS assets; run pnpm build:viewer first");
}

// 3. 生成 TypeScript 常量；插件构建时直接 import，不需要运行时读文件。
await mkdir(path.dirname(outFile), {recursive: true});
await writeFile(outFile, `// Generated by scripts/embed-viewer.mjs. Do not edit by hand.\nexport const VIEWER_HTML = ${JSON.stringify(html)};\n`);
console.log(`embedded viewer (${cssMatches.length} css, ${jsMatches.length} js) -> ${path.relative(root, outFile)}`);
